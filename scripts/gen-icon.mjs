/**
 * 生成应用图标（无第三方依赖）：build/icon.ico（256）+ build/icon.png（512）
 * 画法：圆角渐变方块 + 白色 M
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';

const root = path.resolve(import.meta.dirname, '..');
const outDir = path.join(root, 'build');
fs.mkdirSync(outDir, { recursive: true });

const CRC_TABLE = (() => {
  const table = new Int32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c;
  }
  return table;
})();

function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const typeBuf = Buffer.from(type, 'ascii');
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(Buffer.concat([typeBuf, data])));
  return Buffer.concat([len, typeBuf, data, crc]);
}

function encodePng(width, height, rgba) {
  const raw = Buffer.alloc((width * 4 + 1) * height);
  for (let y = 0; y < height; y++) {
    raw[y * (width * 4 + 1)] = 0;
    rgba.copy(raw, y * (width * 4 + 1) + 1, y * width * 4, (y + 1) * width * 4);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;
  ihdr[9] = 6;
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

/** 点到线段距离 */
function segDist(px, py, x1, y1, x2, y2) {
  const dx = x2 - x1;
  const dy = y2 - y1;
  const len2 = dx * dx + dy * dy || 1;
  let t = ((px - x1) * dx + (py - y1) * dy) / len2;
  t = Math.max(0, Math.min(1, t));
  const cx = x1 + t * dx;
  const cy = y1 + t * dy;
  return Math.hypot(px - cx, py - cy);
}

function draw(size) {
  const buf = Buffer.alloc(size * size * 4);
  const s = size / 256; // 以 256 为设计基准
  const radius = 56 * s;
  const pad = 8 * s;
  const cx = size / 2;
  const cy = size / 2;
  const half = size / 2 - pad;

  // M 的四条笔画（线段 + 粗细），坐标基于 256 设计稿
  const strokes = [
    [80, 180, 80, 76, 12],
    [176, 180, 176, 76, 12],
    [80, 76, 128, 142, 12],
    [176, 76, 128, 142, 12],
  ].map(([x1, y1, x2, y2, w]) => [x1 * s, y1 * s, x2 * s, y2 * s, w * s]);

  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const px = x + 0.5;
      const py = y + 0.5;
      // 圆角矩形覆盖
      const dx = Math.max(Math.abs(px - cx) - (half - radius), 0);
      const dy = Math.max(Math.abs(py - cy) - (half - radius), 0);
      const rectCov = Math.max(0, Math.min(1, radius + 0.5 - Math.hypot(dx, dy)));
      if (rectCov <= 0) continue;

      // 渐变底色
      const t = (px / size + py / size) / 2;
      let r = Math.round(91 + (155 - 91) * t);
      let g = Math.round(140 + (107 - 140) * t);
      let b = Math.round(255 + (255 - 255) * t);

      // 白色 M
      let mCov = 0;
      for (const [x1, y1, x2, y2, w] of strokes) {
        const d = segDist(px, py, x1, y1, x2, y2);
        mCov = Math.max(mCov, Math.max(0, Math.min(1, w + 0.5 - d)));
      }
      if (mCov > 0) {
        r = Math.round(r + (255 - r) * mCov);
        g = Math.round(g + (255 - g) * mCov);
        b = Math.round(b + (255 - b) * mCov);
      }

      const idx = (y * size + x) * 4;
      buf[idx] = r;
      buf[idx + 1] = g;
      buf[idx + 2] = b;
      buf[idx + 3] = Math.round(255 * rectCov);
    }
  }
  return buf;
}

const png256 = encodePng(256, 256, draw(256));
const png512 = encodePng(512, 512, draw(512));
const png64 = encodePng(64, 64, draw(64));

// ICO：单张 256x256 PNG（Windows Vista+ 支持）
const header = Buffer.alloc(6);
header.writeUInt16LE(0, 0);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(1, 4);
const entry = Buffer.alloc(16);
entry[0] = 0; // 256
entry[1] = 0;
entry.writeUInt16LE(1, 4);
entry.writeUInt16LE(32, 6);
entry.writeUInt32LE(png256.length, 8);
entry.writeUInt32LE(22, 12);
fs.writeFileSync(path.join(outDir, 'icon.ico'), Buffer.concat([header, entry, png256]));
fs.writeFileSync(path.join(outDir, 'icon.png'), png512);

// 托盘图标：以 base64 内嵌进主进程，避免安装包额外资源依赖
const iconData = `// AUTO-GENERATED by scripts/gen-icon.mjs — 托盘图标（64x64 PNG base64）
export const TRAY_ICON_B64 = '${png64.toString('base64')}';
`;
fs.mkdirSync(path.join(root, 'src/electron'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/electron/icon-data.ts'), iconData, 'utf-8');
console.log('图标已生成：build/icon.ico（256）、build/icon.png（512）、src/electron/icon-data.ts（托盘 64）');
