import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const html = fs.readFileSync(path.join(root, 'src/server/public/index.html'), 'utf-8');
const out = `// AUTO-GENERATED by scripts/gen-panel.mjs — 编辑 src/server/public/index.html 后重新生成
export const PANEL_HTML = ${JSON.stringify(html)};
`;
fs.writeFileSync(path.join(root, 'src/server/panel-html.ts'), out, 'utf-8');
console.log(`panel-html.ts 生成完成（${(html.length / 1024).toFixed(1)} KB）`);
